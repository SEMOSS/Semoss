package prerna.engine.impl;

import java.util.Map;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;
import org.json.JSONArray;
import org.json.JSONObject;

import prerna.engine.api.IMCP;
import prerna.om.Insight;
import prerna.reactor.agent.mcp.MCPErrorCode;
import prerna.reactor.agent.mcp.MCPUtility;
import prerna.sablecc2.om.execptions.SemossMCPException;

/**
 * MCP implementation that reads tools from the current insight's asset folder
 * ({@code mcp/pixel_mcp.json}) rather than from an engine project.
 *
 * <p>This enables rooms to expose recording-specific tools (generated by
 * {@link prerna.reactor.playwright.MakeRoomPlaywrightMCPReactor}) without
 * registering a separate engine project.  The virtual engine ID for this MCP
 * is the constant {@link #INSIGHT_MCP_ID}.
 *
 * <p>Tools must be Pixel-backed (i.e. listed in {@code pixel_mcp.json}); the
 * execution delegates to {@link MCPUtility#runPixelTool} with a {@code null}
 * engine so the pixel runs directly in the caller's insight context.
 */
public class InsightMCP implements IMCP {

	private static final Logger classLogger = LogManager.getLogger(InsightMCP.class);

	/** Sentinel ID used in {@code room.options.mcp} to reference this MCP. */
	public static final String INSIGHT_MCP_ID = "__insight__";

	/** Display name shown in the room's MCP list. */
	public static final String INSIGHT_MCP_NAME = "Room Recordings";

	/** Relative path within the insight asset folder. */
	private static final String PIXEL_MCP_REL = "/mcp/pixel_mcp.json";

	private final Insight insight;

	public InsightMCP(Insight insight) {
		if (insight == null) {
			throw new IllegalArgumentException("Insight must not be null for InsightMCP");
		}
		this.insight = insight;
	}

	// ── Helpers ───────────────────────────────────────────────────────────────

	private String pixelMcpPath() {
		return insight.getInsightFolder() + PIXEL_MCP_REL;
	}

	// ── IMCP ─────────────────────────────────────────────────────────────────

	@Override
	public JSONObject initMCP(String protocolVersion) {
		JSONObject result = new JSONObject();
		result.put("protocolVersion", protocolVersion);
		JSONObject serverInfo = new JSONObject();
		serverInfo.put("name", INSIGHT_MCP_NAME);
		serverInfo.put("version", "1.0.0");
		result.put("serverInfo", serverInfo);
		JSONObject caps = new JSONObject();
		JSONObject tools = new JSONObject();
		tools.put("listChanged", false);
		caps.put("tools", tools);
		result.put("capabilities", caps);
		return result;
	}

	@Override
	public JSONObject getMCPResources() {
		JSONObject map = new JSONObject();
		map.put("resources", new JSONArray());
		return map;
	}

	@Override
	public JSONObject getMCPResourcesTemplates() {
		JSONObject map = new JSONObject();
		map.put("resourceTemplates", new JSONArray());
		return map;
	}

	@Override
	public JSONObject getMCPPrompts() {
		JSONObject map = new JSONObject();
		map.put("prompts", new JSONArray());
		return map;
	}

	/**
	 * Returns the tool definitions from the insight's {@code mcp/pixel_mcp.json},
	 * adding the standard {@code _meta} block so Playground can resolve the
	 * engine back to this virtual insight MCP.
	 */
	@Override
	public JSONObject getMCPTools() {
		JSONArray tools = MCPUtility.getNode(pixelMcpPath(), "tools");

		JSONObject toolMap = new JSONObject();
		toolMap.put("tools", tools);

		// Engine-level meta: use INSIGHT_MCP_ID as the engine.
		// Individual tools in the JSON may override SMSS_PROJECT_ID with the
		// actual playwright app project ID (set by MakeRoomPlaywrightMCPReactor)
		// so that Playground constructs the correct sidebar URL.
		JSONObject meta = new JSONObject();
		meta.put(MCPUtility.SMSS_PROJECT_ID, INSIGHT_MCP_ID);
		meta.put(MCPUtility.SMSS_PROJECT_NAME, INSIGHT_MCP_NAME);
		meta.put(MCPUtility.SMSS_ENGINE_ID, INSIGHT_MCP_ID);
		meta.put(MCPUtility.SMSS_ENGINE_NAME, INSIGHT_MCP_NAME);
		meta.put(MCPUtility.SMSS_ENGINE_TYPE, "INSIGHT");
		toolMap.put("_meta", meta);

		return toolMap;
	}

	/**
	 * Dispatches the tool call by looking up the function definition in
	 * {@code mcp/pixel_mcp.json} and running it as a Pixel expression via
	 * {@link MCPUtility#runPixelTool}.
	 */
	@Override
	public Object callTool(String toolName, Map<String, Object> params, Insight callerInsight) {
		if (toolName == null || toolName.isBlank()) {
			throw new IllegalArgumentException("Tool name must not be blank");
		}

		// The callerInsight is authoritative (it owns the asset folder);
		// fall back to the constructor insight only if caller is null.
		Insight effectiveInsight = callerInsight != null ? callerInsight : this.insight;
		String pixelPath = effectiveInsight.getInsightFolder() + PIXEL_MCP_REL;

		// Find the tool definition
		JSONArray tools = MCPUtility.getNode(pixelPath, "tools");
		JSONObject toolDef = null;
		for (int i = 0; i < tools.length(); i++) {
			JSONObject t = tools.optJSONObject(i);
			if (t != null && toolName.equals(t.optString("name"))) {
				toolDef = t;
				break;
			}
		}

		if (toolDef == null) {
			throw new SemossMCPException(
					"Tool '" + toolName + "' not found in insight MCP at " + pixelPath,
					MCPErrorCode.RESOURCE_NOT_FOUND);
		}

		// Resolve the actual pixel reactor name from SMSS_FUNCTION_NAME if present
		String functionName = toolName;
		JSONObject toolMeta = toolDef.optJSONObject("_meta");
		if (toolMeta != null && toolMeta.has(MCPUtility.SMSS_FUNCTION_NAME)) {
			functionName = toolMeta.getString(MCPUtility.SMSS_FUNCTION_NAME);
		}

		JSONObject inputSchema = toolDef.optJSONObject("inputSchema");
		JSONObject properties = inputSchema != null ? inputSchema.optJSONObject("properties") : null;
		if (properties == null) {
			properties = new JSONObject();
		}

		classLogger.info("InsightMCP executing tool='{}' function='{}' insightId={}",
				toolName, functionName, effectiveInsight.getInsightId());

		// Run as a plain pixel (no engine context) directly inside the caller's insight
		return MCPUtility.runPixelTool(null, effectiveInsight, functionName, properties, params);
	}
}
